def fetch_institutional_data(stock_id):
    clean_id = stock_id.replace(".TW", "").replace(".TWO", "")
    headers = {"User-Agent": "Mozilla/5.0"}
    
    try:
        if ".TWO" in stock_id:
            # 上櫃 (TPEx)
            url = "https://www.tpex.org.tw/web/stock/3insti/daily_trade/3itrade_hedge_result.php?l=zh-tw&o=json&se=AL"
            res = requests.get(url, headers=headers).json()
            if 'aaData' in res:
                df = pd.DataFrame(res['aaData'])
                target = df[df[0] == clean_id]
                if not target.empty:
                    return f"外資買賣超:{target.iloc[0][4]}股, 投信買賣超:{target.iloc[0][10]}股, 自營商:{target.iloc[0][13]}股, 三大法人合計:{target.iloc[0][14]}股"
        else:
            # 上市 (TWSE)
            url = "https://www.twse.com.tw/rwd/zh/fund/T86?response=json&selectType=ALL"
            res = requests.get(url, headers=headers).json()
            if 'data' in res:
                df = pd.DataFrame(res['data'], columns=res['fields'])
                target = df[df['證券代號'] == clean_id]
                if not target.empty:
                    # 挑選重要欄位
                    cols = ['證券代號', '證券名稱', '外資及陸資買賣超股數', '投信買賣超股數', '自營商買賣超股數', '三大法人買賣超股數']
                    avail_cols = [c for c in cols if c in df.columns]
                    return target[avail_cols].to_csv(index=False)
    except Exception as e:
        return f"官方 API 抓取失敗: {e}"
        
    return "查無今日法人買賣超資料 (可能今日未開盤或代碼非台股)"
